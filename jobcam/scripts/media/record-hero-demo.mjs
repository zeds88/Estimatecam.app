// Record only a fictional project in a disposable browser context. No live APIs.
// Usage: node scripts/media/record-hero-demo.mjs <origin> <output-dir> <photo-path>
import { chromium } from 'playwright'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const [origin = 'http://127.0.0.1:4180', outputArg, photoArg] = process.argv.slice(2)
if (!outputArg || !photoArg) throw Error('Output directory and local field photo are required')
const output = resolve(outputArg)
await mkdir(output, { recursive: true })
const photo = (await readFile(photoArg)).toString('base64')
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, colorScheme: 'light', serviceWorkers: 'block', recordVideo: { dir: output, size: { width: 390, height: 780 } } })
await context.route('https://**/*', (route) => route.abort())
const begun = Date.now()
const page = await context.newPage()
try {
  await page.goto(origin)
  await page.getByRole('link', { name: 'Try the free beta', exact: true }).first().click()
  await page.getByText('No projects yet').waitFor()
  await page.evaluate(async (base64) => {
    const blob = new Blob([Uint8Array.from(atob(base64), (c) => c.charCodeAt(0))], { type: 'image/jpeg' })
    const db = await new Promise((resolve, reject) => { const r = indexedDB.open('jobcam'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) })
    const tx = db.transaction(['projects', 'photos', 'estimates', 'scopes'], 'readwrite')
    const now = Date.now()
    tx.objectStore('projects').put({ id: 'hero-practice', name: 'Courtyard drainage', address: '', customer: '', phone: '', email: '', status: 'active', notes: 'Practice project. Sample scope and rates.', createdAt: now, updatedAt: now })
    tx.objectStore('photos').put({ id: 'hero-photo', projectId: 'hero-practice', kind: 'photo', blob, thumb: blob, width: 900, height: 1600, caption: 'Review the courtyard drainage', tags: ['Before'], annotations: [], takenAt: now })
    tx.objectStore('estimates').put({ id: 'hero-estimate', projectId: 'hero-practice', title: 'Sample estimate', proposal: true, items: [{ id: 'hero-item', description: 'Drainage assessment', qty: 1, unit: 'visit', unitPrice: 0 }], taxRate: 0, createdAt: now })
    tx.objectStore('scopes').put({ id: 'hero-scope', projectId: 'hero-practice', title: 'Drainage assessment', template: { id: 'hero-template', trade: 'Drainage', title: 'Drainage assessment', summary: 'Review the observed courtyard conditions before proposing repairs.', scope: ['Document the existing conditions.', 'Inspect the visible outlet.', 'Confirm the repair scope after inspection.'], included: ['Site observations and photos'], excluded: ['Repair work until the scope is agreed'], assumptions: ['The cause has not yet been confirmed'], warranty: '' }, values: {}, createdAt: now })
    await new Promise((resolve, reject) => { tx.oncomplete = resolve; tx.onerror = () => reject(tx.error) })
    db.close()
  }, photo)
  await page.goto(`${origin}/#/p/hero-practice`)
  await page.getByRole('heading', { name: 'Courtyard drainage', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Review the courtyard drainage', exact: true }).scrollIntoViewIfNeeded()
  await page.waitForTimeout(500)
  const start = (Date.now() - begun) / 1000
  await page.screenshot({ path: `${output}/app-poster.png` })
  await page.waitForTimeout(900)
  await page.getByRole('button', { name: 'Review the courtyard drainage', exact: true }).click()
  await page.waitForTimeout(1400)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /Scope/ }).first().click()
  await page.getByRole('button', { name: /Drainage assessment.*complete/ }).click()
  await page.waitForTimeout(2500)
  await page.getByRole('button', { name: /Estimate/ }).first().click()
  await page.getByLabel('Unit price', { exact: true }).scrollIntoViewIfNeeded()
  await page.getByLabel('Unit price', { exact: true }).fill('')
  await page.getByLabel('Unit price', { exact: true }).press('ControlOrMeta+A')
  await page.getByLabel('Unit price', { exact: true }).pressSequentially('125', { delay: 180 })
  await page.getByLabel('Unit price', { exact: true }).blur()
  await page.waitForTimeout(2800)
  await page.getByRole('button', { name: /Photos/ }).first().click()
  await page.getByRole('button', { name: 'Review the courtyard drainage', exact: true }).scrollIntoViewIfNeeded()
  await page.waitForTimeout(2100)
  const duration = (Date.now() - begun) / 1000 - start
  const video = page.video()
  await page.close()
  await video.saveAs(`${output}/app-session.webm`)
  await writeFile(`${output}/recording.json`, JSON.stringify({ start, duration, viewport: { width: 390, height: 780 }, project: 'Fictional courtyard drainage', rates: 'Illustrative only; entered in a disposable local context', source: 'Actual Estimate Cam browser UI', audio: false, actual_remote_api_calls: 0 }, null, 2) + '\n')
  console.log(JSON.stringify({ start, duration, video: `${output}/app-session.webm` }))
} finally { await context.close(); await browser.close() }
